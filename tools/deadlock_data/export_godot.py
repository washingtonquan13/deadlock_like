#!/usr/bin/env python3
"""Export normalized reference CSVs to JSON the Godot project can load for
side-by-side comparison / debug overlays.

Output: data/reference_godot/deadlock_reference.json (+ one file per table).

THIS IS REFERENCE ONLY. The game must use its own tuned values in data/
(heroes/, items/, ...). Do not ship these files; they describe another game.

  python export_godot.py
  python export_godot.py --tables heroes items --split
"""
from __future__ import annotations

import argparse
import csv
import json

from common import GODOT_REF_DIR, REF_DIR, ensure_dirs, utc_now_iso

TABLES = {  # table -> (csv, key column)
    "heroes": ("heroes.csv", "class_name"),
    "abilities": ("abilities.csv", "class_name"),
    "items": ("items.csv", "class_name"),
    "npc_units": ("npc_units.csv", "class_name"),
    "economy": ("economy.csv", "key"),
    "hero_stats": ("analytics_hero_stats.csv", "hero_id"),
    "item_stats": ("analytics_item_stats.csv", "item_id"),
    "game_stats": ("analytics_game_stats.csv", "key"),
}
JSON_COLS = {"key_properties_json", "properties_json"}


def coerce(v: str):
    if v is None or v == "":
        return None
    if v in ("True", "true"):
        return True
    if v in ("False", "false"):
        return False
    try:
        x = float(v)
        return int(x) if x.is_integer() and "." not in v else x
    except ValueError:
        pass
    if v[:1] in "[{":
        try:
            return json.loads(v)
        except ValueError:
            pass
    return v


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--tables", nargs="*", default=list(TABLES))
    ap.add_argument("--split", action="store_true", help="also write one JSON per table")
    args = ap.parse_args(argv)
    ensure_dirs()
    out = {
        "_meta": {
            "reference_only": True,
            "warning": ("REFERENCE ONLY - numbers observed from Deadlock via public community APIs. "
                        "Do NOT use as game data; our game uses its own tuned values in res://data/."),
            "generated_at": utc_now_iso(),
            "generator": "tools/deadlock_data/export_godot.py",
            "units": {"distance_engine_units_to_m": 0.0254,
                      "move_speed": "m/s", "time": "s", "wpn_*_range": "engine units (see _m columns)"},
            "provenance": {},
        }
    }
    for t in args.tables:
        fname, key = TABLES[t]
        p = REF_DIR / fname
        if not p.exists():
            print(f"  skip {t}: {fname} missing (run normalize.py)")
            continue
        with p.open(encoding="utf-8") as f:
            rows = list(csv.DictReader(f))
        table = {}
        for r in rows:
            prov = r.pop("provenance", None)
            st = r.pop("source_type", None)
            out["_meta"]["provenance"].setdefault(t, {"source_type": st, "provenance": prov})
            obj = {k: (json.loads(v) if k in JSON_COLS and v else coerce(v)) for k, v in r.items()}
            table[str(r.get(key))] = obj
        out[t] = table
        if args.split:
            (GODOT_REF_DIR / f"{t}.json").write_text(
                json.dumps({"_meta": {**out["_meta"], "provenance": out["_meta"]["provenance"].get(t)},
                            t: table}, indent=1, ensure_ascii=False), encoding="utf-8")
        print(f"  {t}: {len(table)} records")
    path = GODOT_REF_DIR / "deadlock_reference.json"
    path.write_text(json.dumps(out, indent=1, ensure_ascii=False), encoding="utf-8")
    (GODOT_REF_DIR / "README_REFERENCE_ONLY.txt").write_text(
        "Files in this folder are REFERENCE ONLY observations of Deadlock (Valve), generated by\n"
        "tools/deadlock_data/export_godot.py from public community APIs. They are not our game's\n"
        "data, must not be shipped, and must not be loaded by gameplay code. Use them only for\n"
        "design comparison / debug overlays. Our tuned values live in res://data/.\n", encoding="utf-8")
    print(f"  wrote {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
